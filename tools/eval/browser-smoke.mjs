// Real browser/rendering integration; only the AI boundary is injected.
// Run explicitly with npm run test:browser (no provider key or paid call).
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import { chromium } from 'playwright';
import { startServer } from './server.mjs';
import { resolveChromiumExecutable } from './src/render.mjs';
const root = path.resolve(process.env.IMSTAGE_EVAL_TEST_DIR || '.local/eval-test');
await fs.mkdir(root, { recursive: true });
const dir = await fs.mkdtemp(path.join(root, 'browser-'));
let modelCalls = 0;
const scene = { title: '周末露营', platform: 'wechat', selfId: 'me', deviceTime: '09:41', date: '', watermark: '', participants: [{ id: 'me', name: '我' }, { id: 'lin', name: '小林' }], messages: [{ id: 'm1', participantId: 'lin', type: 'text', text: '周末要不要去露营？', time: '09:40' }, { id: 'm2', participantId: 'me', type: 'text', text: '好啊，我想带小狗。', time: '09:41' }] };
const server = await startServer({ port: 0, dataDir: path.join(dir, 'data'), aiConfig: { configured: true, model: 'injected-test' }, generateScene: async ({ request, signal }) => {
  modelCalls++;
  if (request.text === 'cancel-test') await new Promise((resolve, reject) => { const timer = setTimeout(resolve, 5000); signal.addEventListener('abort', () => { clearTimeout(timer); reject(new Error('cancelled')); }, { once: true }); });
  return { rawContent: JSON.stringify({ scene: { ...scene, platform: request.targetIM } }), model: 'injected-test' };
} });
const browser = await chromium.launch({ headless: true, ...(resolveChromiumExecutable() ? { executablePath: resolveChromiumExecutable() } : {}) });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const errors = [];
page.on('pageerror', (error) => errors.push(error.message));
const url = `http://127.0.0.1:${server.address().port}`;
const state = async () => (await (await fetch(`${url}/api/store`)).json());
const waitSaved = () => page.waitForFunction(() => document.getElementById('save-review').textContent === '标注已保存');
try {
  await page.goto(url);
  await page.waitForFunction(() => document.getElementById('generation-hint').textContent.includes('自动识别'));
  assert.equal(await page.locator('#generate').isDisabled(), true);
  await page.locator('#collection-tools').click();
  await page.locator('#export-synthetic').click();
  await page.locator('#notice').waitFor({ state: 'visible' });
  assert.equal(await page.locator('#tools-dialog').isVisible(), false, 'empty export feedback must be visible outside modal');
  assert.equal(await page.locator('#target-im').inputValue(), 'wechat');
  await page.locator('#note-text').fill('周末露营，带小狗。');
  await page.locator('#synthetic').check();
  await page.reload();
  assert.equal(await page.locator('#note-text').inputValue(), '周末露营，带小狗。');
  await page.locator('#generate').click();
  await page.locator('#result-view').waitFor({ state: 'visible' });
  await page.locator('#result-image').evaluate((img) => img.decode());
  const first = (await state()).cases[0];
  assert.equal(first.width, 390); assert.equal(first.height, 844); assert.equal(first.review, null);
  await page.locator('#judge-bad').click();
  assert.equal(await page.locator('#save-review').isDisabled(), true);
  await page.locator('#review-reason').fill('尾部不完整');
  await page.locator('[data-issue="completeness"]').click();
  await page.locator('#new-note').click();
  await page.locator('#confirm-dialog').waitFor({ state: 'visible' });
  await page.locator('#confirm-dialog button[value="cancel"]').click();
  assert.equal(await page.locator('#result-view').isVisible(), true);
  await page.locator('#save-review').click(); await waitSaved();
  assert.equal((await state()).cases[0].review.scores.completeness, 0);
  assert.equal(await page.locator('#golden-area').isVisible(), false);
  await page.locator('#judge-good').click();
  await page.locator('#review-reason').fill('冲突恢复后保留这段评价');
  await page.route('**/api/cases/*/review', async (route) => route.fulfill({ status: 409, contentType: 'application/json', body: JSON.stringify({ code: 'revision_conflict', error: 'revision changed' }) }));
  await page.locator('#save-review').click();
  await page.locator('#notice-retry').waitFor({ state: 'visible' });
  await page.unroute('**/api/cases/*/review');
  await page.locator('#notice-retry').click();
  await page.waitForFunction(() => document.getElementById('notice').hidden);
  assert.equal(await page.locator('#review-reason').inputValue(), '冲突恢复后保留这段评价');
  assert.equal(await page.locator('#judge-good').getAttribute('aria-pressed'), 'true');
  await page.locator('#save-review').click(); await waitSaved();
  await page.locator('#promote').click();
  await page.waitForFunction(() => document.getElementById('review-status').textContent === '已确认为金标');
  await page.locator('#collection-tools').click();
  const downloadEvent = page.waitForEvent('download');
  await page.locator('#export-synthetic').click();
  const download = await downloadEvent;
  const bundlePath = path.join(dir, 'bundle.json'); await download.saveAs(bundlePath);
  assert.equal(JSON.parse(await fs.readFile(bundlePath, 'utf8')).cases.length, 1);
  await page.locator('#import-file').setInputFiles(bundlePath);
  await page.waitForFunction(() => document.getElementById('case-count').textContent === '2');
  assert.equal((await state()).cases.length, 2);
  await page.locator('#new-note').click();
  assert.equal(await page.locator('#note-text').inputValue(), '');
  assert.equal(await page.locator('#synthetic').isChecked(), false, 'a new note must not inherit public-data consent');
  // Paste an actual PNG through the composer's clipboard handler.
  const png = Buffer.from(await (await fetch(`${url}/api/cases/${first.id}/candidate.png`)).arrayBuffer());
  await page.locator('#compose-form').evaluate((form, bytes) => {
    const dt = new DataTransfer(); dt.items.add(new File([new Uint8Array(bytes)], 'chat.png', { type: 'image/png' }));
    form.dispatchEvent(new ClipboardEvent('paste', { clipboardData: dt, bubbles: true, cancelable: true }));
  }, [...png]);
  await page.locator('#input-images img').waitFor();
  await page.reload(); await page.locator('#input-images img').waitFor();
  await page.locator('#target-im').selectOption('telegram');
  await page.locator('#output-kind').selectOption('long-screenshot');
  await page.locator('#generate').click(); await page.locator('#result-view').waitFor({ state: 'visible' });
  await page.locator('#result-image').evaluate((img) => img.decode());
  const imageCase = (await state()).cases.at(-1);
  assert.equal(imageCase.generation.input.text, ''); assert.equal(imageCase.attachments.length, 1); assert.equal(imageCase.targetIM, 'telegram');
  assert.equal(imageCase.outputKind, 'long-screenshot');
  assert.ok(imageCase.height < 844, 'short long-mode content must not be padded to the initial browser viewport');
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.locator('#new-note').click();
  const spacing = await page.evaluate(() => ({ optionBottom: document.querySelector('.options').getBoundingClientRect().bottom, actionTop: document.getElementById('generate').getBoundingClientRect().top }));
  assert.ok(spacing.actionTop >= spacing.optionBottom, 'mobile target options must not overlap generation action');
  await page.locator('#note-text').fill('cancel-test');
  await page.locator('#generate').click();
  await page.locator('#cancel-generation').click();
  await page.locator('#composer-view').waitFor({ state: 'visible' });
  assert.equal(await page.locator('#note-text').inputValue(), 'cancel-test');
  assert.equal((await state()).cases.length, 3);
  // A transient HTTP failure preserves both text and request ID.
  await page.locator('#note-text').fill('network-test');
  let requestId;
  await page.route('**/api/generate', async (route) => { requestId = route.request().postDataJSON().requestId; await route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ error: '临时不可用', code: 'test_unavailable' }) }); });
  await page.locator('#generate').click();
  await page.locator('#composer-view').waitFor({ state: 'visible' });
  assert.equal(await page.locator('#note-text').inputValue(), 'network-test');
  await page.reload();
  assert.equal(await page.evaluate(() => JSON.parse(localStorage.getItem('imstage.scene-note.v1')).requestId), requestId);
  await page.unroute('**/api/generate');
  await page.locator('#generate').click(); await page.locator('#result-view').waitFor({ state: 'visible' });
  assert.equal((await state()).cases.at(-1).generation.requestId, requestId);
  assert.deepEqual(errors, []);
  console.log(JSON.stringify({ pass: true, modelBoundary: 'injected; no paid calls', modelCalls, checks: ['note defaults', 'draft reload', 'real PNG render', 'bad reason + scores', 'unsaved cancel dialog', 'good/golden gate', 'export/import', 'image clipboard paste + reload', 'long PNG', 'mobile width', 'cancel retains input', 'HTTP failure + same-ID retry', 'empty export feedback', 'review conflict retains draft', 'mobile option separation'] }));
} finally {
  await browser.close(); await new Promise((resolve) => server.close(resolve));
  await fs.rm(dir, { recursive: true, force: true });
}
