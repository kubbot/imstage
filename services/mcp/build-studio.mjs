import { build } from 'vite';
import react from '@vitejs/plugin-react';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import fs from 'node:fs/promises';
import { createHash } from 'node:crypto';
const root = fileURLToPath(new URL('../../', import.meta.url));
// Compile the same SceneView used by the Web export; never run a dev server.
// https://vite.dev/guide/ssr#building-for-production
const result = await build({
  configFile: false, root, plugins: [react()], logLevel: 'warn',
  build: {
    ssr: path.join(root, 'services/mcp/studio-entry.tsx'),
    outDir: path.join(root, '.local/mcp-renderer'), emptyOutDir: true, write: false,
    rollupOptions: { output: { entryFileNames: 'studio.mjs' } },
  },
});
const output = result.output;
if (output.length !== 1 || output[0].type !== 'chunk') throw new Error('Expected one self-contained studio SSR chunk');
const css = await fs.readFile(path.join(root, 'apps/web/src/studio/studio.css'), 'utf8');
// Include every bundled source, CSS, compiler script and lockfile. Relative
// paths and normalized newlines keep the artifact identical across CI hosts.
const inputs = [...new Set([...Object.keys(output[0].modules), path.join(root,'apps/web/src/studio/studio.css'), fileURLToPath(import.meta.url), path.join(root,'package-lock.json')])].sort();
const digest = createHash('sha256');
for (const file of inputs) {
  digest.update(path.relative(root,file).split(path.sep).join('/')+'\n');
  digest.update((await fs.readFile(file,'utf8')).replace(/\r\n/g,'\n'));
}
const code = `// Generated by npm run build:mcp. Do not edit.\n// Source SHA-256: ${digest.digest('hex')}\n` + output[0].code + `\nexport const STUDIO_CSS = ${JSON.stringify(css.replace(/\r\n/g,'\n'))};\n`;
const generated = path.join(root,'packages/renderer/generated/studio.mjs');
if (process.argv.includes('--check')) {
  if (await fs.readFile(generated,'utf8').catch(()=>null) !== code) throw new Error('Stale shared renderer: run npm run build:mcp and commit the generated artifact.');
} else {
  await fs.mkdir(path.dirname(generated),{recursive:true});
  await fs.writeFile(generated,code);
  // Keep the existing test/debug import location. Production needs no .local.
  const local = path.join(root,'.local/mcp-renderer/studio.mjs');
  await fs.mkdir(path.dirname(local),{recursive:true});
  await fs.writeFile(local,code);
}
